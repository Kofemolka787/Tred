"use strict";
const assert=require('node:assert/strict'),vm=require('node:vm'),fs=require('node:fs');
let now=1800000000000,timers=[],sent=[];
const context={window:{},Date:class extends Date{static now(){return now;}},setTimeout:fn=>{timers.push(fn);return timers.length;},clearTimeout:()=>{}};
vm.createContext(context);vm.runInContext(fs.readFileSync('connector/market-scan.js','utf8'),context);
const scanner=context.window.__tredMarketScanner,feed='11111111-1111-4111-8111-111111111111';
const state={feed,catalog:new Map([['AAA',{is_open:true}],['BBB',{is_open:false}],['CCC',{is_open:true}]]),requests:new Map()};
scanner.attach({readyState:1},state,frame=>sent.push(JSON.parse(frame.slice(2))));
const plan={version:1,until:now/1000+15,offset:7200,pairs:[{symbol:'AAA',feed_id:feed,quote:false,history:[{period:60,bars:160},{period:300,bars:160}]},{symbol:'BBB',feed_id:feed,quote:false,history:[{period:60,bars:160}]}]};
assert.equal(scanner.plan({...plan,pairs:[{...plan.pairs[0],history:[{period:1,bars:999999}]}]}).code,'request_failed');
assert.equal(scanner.plan(plan).code,'ready');
const tick=()=>{now+=400;const tasks=timers;timers=[];for(const fn of tasks)fn();};
for(let i=0;i<20;i++)tick();
assert.equal(sent.length,2,'One outstanding history per instrument; a closed instrument sends nothing');
assert.deepEqual(sent.map(f=>f[0]),['subfor','loadHistoryPeriod']);
assert(sent.slice(1).every(f=>f[1].time>=1800007200&&f[1].time%f[1].period===0));
scanner.plan({...plan,until:now/1000+15,pairs:[...plan.pairs,{symbol:'CCC',feed_id:feed,quote:false,history:[{period:60,bars:160}]}]});
for(let i=0;i<2;i++)tick();
assert(sent.some(f=>f[0]==='subfor'&&f[1]==='CCC'),'Unvisited symbols progress while histories wait');
const request=sent.find(f=>f[0]==='loadHistoryPeriod')[1];scanner.received(state,{asset:'AAA',index:request.index},request.period);
for(let i=0;i<2;i++)tick();
assert(sent.some(f=>f[0]==='loadHistoryPeriod'&&f[1].asset==='CCC'));
scanner.close(feed);const count=sent.length;for(let i=0;i<30;i++)tick();assert.equal(sent.length,count);
scanner.stop();assert(sent.every(f=>['subfor','loadHistoryPeriod'].includes(f[0])));
sent=[];timers=[];
const second={feed:'22222222-2222-4222-8222-222222222222',catalog:new Map([['AAA',{is_open:true}]]),requests:new Map()};
scanner.attach({readyState:1},second,frame=>sent.push(JSON.parse(frame.slice(2))));
const recovery={version:1,until:now/1000+15,offset:7200,pairs:[{symbol:'AAA',feed_id:second.feed,quote:true,history:[]}]};
scanner.plan(recovery);for(let i=0;i<5;i++)tick();
const probe=sent.find(f=>f[0]==='loadHistoryPeriod')[1];
assert.equal(probe.period,1);assert.equal(probe.offset,20);
assert(Math.abs(probe.time-(now/1000+7200))<3,'A tick request ends at current native time, not a closed candle boundary');
scanner.received(second,{asset:'AAA',index:probe.index},1);
scanner.quoted(second,'AAA',now/1000+7200);
const quiet=sent.length;for(let i=0;i<12;i++)tick();assert.equal(sent.length,quiet,'Fresh observed ticks stop unnecessary probes');
for(let i=0;i<85;i++){if(i%10===0)scanner.plan({...recovery,until:now/1000+15});tick();}
assert(sent.filter(f=>f[0]==='subfor').length>=2,'A failed or silent subscription must be retried');
assert(sent.filter(f=>f[0]==='loadHistoryPeriod').length>=2,'Quote probes resume only when prices stop');
scanner.close(second.feed);scanner.stop();
sent=[];timers=[];
const third={feed:'33333333-3333-4333-8333-333333333333',catalog:new Map([['AAA',{is_open:true}],['CCC',{is_open:true}]]),requests:new Map()};
scanner.attach({readyState:1},third,frame=>sent.push(JSON.parse(frame.slice(2))));
scanner.plan({...plan,until:now/1000+15,pairs:['AAA','CCC'].map(symbol=>({symbol,feed_id:third.feed,quote:false,history:[{period:60,bars:160},{period:300,bars:160}]}))});
for(let i=0;i<4;i++)tick();
assert.equal(sent.filter(f=>f[0]==='loadHistoryPeriod').length,2,'Both slots can serve different instruments');
const first=sent.find(f=>f[0]==='loadHistoryPeriod')[1];
scanner.received(third,{asset:first.asset},300);
const beforeWrong=sent.length;tick();assert.equal(sent.length,beforeWrong,'A different period cannot free the pending slot');
scanner.received(third,{asset:first.asset},60);
tick();assert.equal(sent.length,beforeWrong+1,'A response without index but verified symbol/period frees the slot immediately');
const next=sent.at(-1)[1];scanner.received(third,{asset:next.asset,index:String(next.index)},next.period);
tick();
scanner.close(third.feed);scanner.stop();
sent=[];timers=[];
const fourth={feed:'44444444-4444-4444-8444-444444444444',catalog:new Map(['AAA','CCC','DDD'].map(s=>[s,{is_open:true}])),requests:new Map()};
scanner.attach({readyState:1},fourth,frame=>sent.push(JSON.parse(frame.slice(2))));
scanner.plan({...plan,until:now/1000+15,pairs:['AAA','CCC','DDD'].map(symbol=>({symbol,feed_id:fourth.feed,quote:false,history:[{period:60,bars:160}]}))});
now+=400;scanner.wake();assert.equal(sent.length,1);
for(let i=0;i<1000;i++)scanner.wake();
assert.equal(sent.length,1,'An incoming-message burst cannot multiply the request budget');
now+=399;scanner.wake();assert.equal(sent.length,1);
now+=1;scanner.wake();assert.equal(sent.length,2);
const due=timers;timers=[];for(const fn of due)fn();
assert.equal(sent.length,2,'Timer and message wakes share one pacing guard');
scanner.close(fourth.feed);scanner.stop();
sent=[];timers=[];
const paging={feed:'55555555-5555-4555-8555-555555555555',catalog:new Map([['AAA',{is_open:true}]]),requests:new Map()};
scanner.attach({readyState:1},paging,frame=>sent.push(JSON.parse(frame.slice(2))));
const boundary=Math.floor(now/1000/300)*300-24*300;
const pagePlan={version:1,until:now/1000+15,offset:7200,pairs:[{symbol:'AAA',feed_id:paging.feed,quote:false,history:[{period:300,bars:160,before:boundary}]}]};
for(const before of [now/1000+300,boundary+.5,boundary+2,boundary-2000*300])assert.equal(scanner.plan({...pagePlan,pairs:[{...pagePlan.pairs[0],history:[{period:300,bars:160,before}]}]}).code,'request_failed');
scanner.plan(pagePlan);for(let i=0;i<3;i++)tick();
const older=sent.find(f=>f[0]==='loadHistoryPeriod')[1];
assert.equal(older.time,boundary+7200,'Only the explicit source offset applies to a historical end bound');
scanner.received(paging,{asset:'AAA',index:older.index},300);
scanner.plan({...pagePlan,until:now/1000+15,pairs:[{...pagePlan.pairs[0],history:[{period:300,bars:160,before:boundary-24*300}]}]});
tick();
assert.equal(sent.at(-1)[1].time,boundary-24*300+7200,'An older page progresses without the same-page retry cooldown');
scanner.close(paging.feed);scanner.stop();
assert(sent.every(f=>f[0]!=='changeSymbol'),'The foreground path cannot change its chart');
sent=[];timers=[];
const native={feed:'66666666-6666-4666-8666-666666666666',catalog:new Map([['AAA',{is_open:true}],['CCC',{is_open:true}]]),requests:new Map()};
scanner.attach({readyState:1},native,frame=>sent.push(JSON.parse(frame.slice(2))));
const nativePlan={version:1,until:now/1000+15,offset:7200,dedicated:true,pairs:['AAA','CCC'].map(symbol=>({symbol,feed_id:native.feed,quote:false,history:[{period:300,bars:160}]}))};
now+=400;
scanner.plan(nativePlan);assert.equal(sent[0][0],'changeSymbol','Only the dedicated tab initializes native chart history');
tick();assert.equal(sent[1][0],'subfor');
for(let i=0;i<3;i++)tick();assert.equal(sent.filter(f=>f[0]==='changeSymbol').length,1,'Native chart requests are serialized');
scanner.received(native,{asset:'AAA'},60,'updateHistory');tick();
assert.equal(sent.filter(f=>f[0]==='changeSymbol').length,1,'A different period cannot release the chart request');
scanner.received(native,{asset:'AAA'},300,'updateHistory');tick();
assert.equal(sent.filter(f=>f[0]==='changeSymbol').length,2);
scanner.close(native.feed);scanner.stop();
sent=[];timers=[];now+=400;
const focused={feed:'77777777-7777-4777-8777-777777777777',catalog:new Map([['AAA',{is_open:true}]]),requests:new Map()};
scanner.attach({readyState:1},focused,frame=>sent.push(JSON.parse(frame.slice(2))));
const focusPlan={version:1,until:now/1000+15,offset:7200,dedicated:true,pairs:[{symbol:'AAA',feed_id:focused.feed,priority:true,quote:true,chart_period:300,history:[]}]};
scanner.plan(focusPlan);assert.equal(sent[0][0],'changeSymbol','A chosen pair can recover its live quote through the native chart even when advanced ticks are empty');
tick();assert.equal(sent[1][0],'subfor');scanner.received(focused,{asset:'AAA'},300,'updateHistory');scanner.quoted(focused,'AAA',now/1000+7200);
for(let i=0;i<10;i++)tick();assert.equal(sent.filter(f=>f[0]==='changeSymbol').length,1,'Fresh native prices suppress redundant chart focus');
for(let i=0;i<6;i++)tick();assert.equal(sent.filter(f=>f[0]==='changeSymbol').length,2,'Focused recovery resumes before the final live-price guard expires');
scanner.close(focused.feed);scanner.stop();
